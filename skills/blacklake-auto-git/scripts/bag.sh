#!/usr/bin/env bash
# bag.sh — blacklake-auto-git, Agent side (Windows Git Bash / Linux / macOS).
#
# The Agent never talks to GitLab or the intranet. It only talks to the airlock
# on the intranet Mac over ssh (user "airlock", forced command), which validates
# every push, relays it to GitLab and opens a Draft MR.
#
# Usage: bag.sh <command> [args]     (bag.sh help for the list)
# Output contract: human-readable lines; the LAST line of every command is
#   RESULT ok ...            or
#   RESULT fail code=<CODE> ...   (see references/troubleshooting.md)
set -uo pipefail

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BAG_VERSION="$(cat "$SKILL_DIR/VERSION" 2>/dev/null || echo 0.0.0)"
BAG_HOME="${BAG_HOME:-$HOME/.blacklake-auto-git}"
STATE="$BAG_HOME/state.env"
SSHCFG="$BAG_HOME/ssh_config"
KNOWN="$BAG_HOME/known_hosts"
KEY="$BAG_HOME/id_ed25519"
ALIAS="bag-airlock"
mkdir -p "$BAG_HOME"

# ----------------------------------------------------------------- helpers
info() { printf '[bag] %s\n' "$*"; }
warn() { printf '[bag] WARN %s\n' "$*" >&2; }
ok()   { printf 'RESULT ok %s\n' "$*"; exit 0; }
fail() { local code="$1"; shift; printf 'RESULT fail code=%s %s\n' "$code" "$*"; hist "fail" "$code $*"; exit 1; }
hist() { printf '%s\t%s\t%s\n' "$(date '+%Y-%m-%dT%H:%M:%S')" "$1" "$2" >> "$BAG_HOME/history.log"; }
have() { command -v "$1" >/dev/null 2>&1; }

load_state() {
  HOST=""; IP=""; FP=""; AUSER="airlock"; REPO_DIR=""; PREFIX="deans-cc/"; TARGET="main"; PAIRED_AT=""
  # shellcheck disable=SC1090
  [ -f "$STATE" ] && . "$STATE"
}
save_state() {
  {
    for k in HOST IP FP AUSER REPO_DIR PREFIX TARGET PAIRED_AT; do
      printf '%s=%q\n' "$k" "${!k-}"
    done
  } > "$STATE.tmp" && mv "$STATE.tmp" "$STATE"
}

ssh_cmd() {
  if [ -n "${BAG_SSH:-}" ]; then echo "$BAG_SSH"; else echo "ssh -F \"$SSHCFG\""; fi
}
gate() {  # gate <command...>   -> runs a whitelisted command on the airlock
  if [ -n "${BAG_SSH:-}" ]; then
    local sc; read -ra sc <<< "$BAG_SSH"; "${sc[@]}" "$ALIAS" "$@"
  else
    ssh -F "$SSHCFG" "$ALIAS" "$@"
  fi
}

write_ssh_config() {  # write_ssh_config <hostname-or-ip>
  cat > "$SSHCFG" <<EOF
# generated by blacklake-auto-git — do not edit by hand (bag.sh pair / doctor rewrite it)
Host $ALIAS
  HostName $1
  User ${AUSER:-airlock}
  IdentityFile "$KEY"
  IdentitiesOnly yes
  HostKeyAlias $ALIAS
  UserKnownHostsFile "$KNOWN"
  StrictHostKeyChecking yes
  BatchMode yes
  ConnectTimeout 6
  ServerAliveInterval 15
  ServerAliveCountMax 4
  LogLevel ERROR
EOF
}

fp_of_keyline() {  # stdin: "<host> <type> <key>" -> SHA256:...
  local tmp; tmp="$(mktemp)"; cat > "$tmp"
  ssh-keygen -lf "$tmp" 2>/dev/null | awk '{print $2}' | head -1
  rm -f "$tmp"
}

keyscan_match() {  # keyscan_match <host> -> prints the keyline if fingerprint == $FP
  local line
  line="$(ssh-keyscan -T 3 -t ed25519 "$1" 2>/dev/null | grep -v '^#' | head -1)"
  [ -n "$line" ] || return 1
  if [ "$(echo "$line" | fp_of_keyline)" = "$FP" ]; then echo "$line"; return 0; fi
  return 2
}

local_ipv4s() {
  {
    if have powershell.exe; then
      powershell.exe -NoProfile -Command "Get-NetIPAddress -AddressFamily IPv4 | ForEach-Object { \$_.IPAddress }" 2>/dev/null
    fi
    if have ipconfig; then ipconfig 2>/dev/null | grep -aoE '([0-9]{1,3}\.){3}[0-9]{1,3}'; fi
    if have ip; then ip -4 -o addr show 2>/dev/null | awk '{print $4}' | cut -d/ -f1; fi
    if have ifconfig; then ifconfig 2>/dev/null | awk '/inet /{print $2}'; fi
    if [ "$(uname -s)" = "Linux" ]; then hostname -I 2>/dev/null | tr ' ' '\n'; fi
  } | tr -d '\r' | grep -E '^([0-9]{1,3}\.){3}[0-9]{1,3}$' \
    | grep -vE '^(127\.|169\.254\.|0\.|255\.)' | sort -u
}

discover() {  # scan local /24 subnets for an ssh host whose ed25519 key == $FP
  [ -n "$FP" ] || return 1
  local hosts; hosts="$(mktemp)"
  local_ipv4s | awk -F. '{print $1"."$2"."$3}' | sort -u | while read -r net; do
    for i in $(seq 1 254); do echo "$net.$i"; done
  done > "$hosts"
  [ -s "$hosts" ] || { rm -f "$hosts"; return 1; }
  info "scanning $(wc -l < "$hosts" | tr -d ' ') addresses on local subnets for the airlock host key..." >&2
  local found=""
  while read -r line; do
    [ -z "$line" ] && continue
    case "$line" in \#*) continue;; esac
    if [ "$(echo "$line" | fp_of_keyline)" = "$FP" ]; then found="$(echo "$line" | awk '{print $1}')"; break; fi
  done < <(ssh-keyscan -T 3 -t ed25519 -f "$hosts" 2>/dev/null)
  rm -f "$hosts"
  [ -n "$found" ] || return 1
  echo "$found"
}

# ----------------------------------------------------------------- commands
cmd_init() {
  have git || fail E_LOCAL_NO_GIT "install Git for Windows (includes Git Bash + ssh)"
  have ssh || fail E_LOCAL_NO_SSH "ssh not found; use Git Bash from Git for Windows"
  have ssh-keygen || fail E_LOCAL_NO_SSH "ssh-keygen not found"
  if [ ! -f "$KEY" ]; then
    ssh-keygen -q -t ed25519 -N "" -C "blacklake-auto-git@$(hostname)" -f "$KEY" || fail E_LOCAL_KEYGEN "ssh-keygen failed"
    info "created agent key $KEY"
  fi
  chmod 600 "$KEY" 2>/dev/null || true
  info "agent public key (embedded into the Mac installer by 'bag.sh bundle'):"
  cat "$KEY.pub"
  ok "init"
}

cmd_bundle() {  # bundle --gitlab-url URL [--prefix P] [--target T] [--out DIR]
  local url="" prefix="deans-cc/" target="main" out="$BAG_HOME/bundle"
  while [ $# -gt 0 ]; do
    case "$1" in
      --gitlab-url) url="$2"; shift;; --prefix) prefix="$2"; shift;;
      --target) target="$2"; shift;; --out) out="$2"; shift;; *) fail E_USAGE "unknown option $1";;
    esac; shift
  done
  case "$url" in https://*|http://*) ;; *) fail E_USAGE "--gitlab-url must be the project's HTTPS clone URL";; esac
  case "$prefix" in */) ;; *) prefix="$prefix/";; esac
  [ -f "$KEY.pub" ] || cmd_init >/dev/null
  mkdir -p "$out"
  local f="$out/blacklake-airlock-installer.sh" pub
  pub="$(cat "$KEY.pub")"
  # values are embedded inside "..." in bash: refuse characters that could break out
  case "$url$prefix$target$pub" in *'"'*|*'$'*|*'`'*|*'\\'*) fail E_USAGE "illegal character in url/prefix/target/key";; esac
  echo "$prefix$target" | grep -qE '^[A-Za-z0-9._/-]+$' || fail E_USAGE "prefix/target may only contain A-Z a-z 0-9 . _ / -"
  # literal placeholder replacement (awk gsub would treat & and \ specially)
  BAG_V="$BAG_VERSION" BAG_U="$url" BAG_P="$prefix" BAG_T="$target" BAG_K="$pub" awk '
    function rep(line, ph, val,   i, out) {
      out = ""
      while ((i = index(line, ph)) > 0) { out = out substr(line, 1, i - 1) val; line = substr(line, i + length(ph)) }
      return out line
    }
    { $0 = rep($0, "__BAG_VERSION__", ENVIRON["BAG_V"]); $0 = rep($0, "__BAG_GITLAB_URL__", ENVIRON["BAG_U"])
      $0 = rep($0, "__BAG_PREFIX__", ENVIRON["BAG_P"]);   $0 = rep($0, "__BAG_TARGET__", ENVIRON["BAG_T"])
      $0 = rep($0, "__BAG_PUBKEY__", ENVIRON["BAG_K"]); print }' "$SKILL_DIR/scripts/mac/install.sh" | tr -d '\r' > "$f"
  {
    echo ""
    echo "# ---- payload: airlock.py (blacklake-auto-git $BAG_VERSION) ----"
    echo ": <<'__AIRLOCK_PY_END__'"   # keeps 'bash -n' happy; never executed (exit above)
    echo "__AIRLOCK_PY_BEGIN__"
    tr -d '\r' < "$SKILL_DIR/scripts/mac/airlock.py"   # CRLF from a Windows checkout would break the Mac
    echo "__AIRLOCK_PY_END__"
  } >> "$f"
  load_state; PREFIX="$prefix"; TARGET="$target"; save_state
  local sum; sum="$( (sha256sum "$f" 2>/dev/null || shasum -a 256 "$f") | awk '{print $1}')"
  info "installer: $f"
  info "sha256:    $sum"
  info "Transfer it to the Mac (any of): bag.sh serve-bundle (same hotspot) | AirDrop/WeChat/USB."
  info "On the Mac run:  sudo bash blacklake-airlock-installer.sh"
  ok "bundle path=$f sha256=$sum"
}

cmd_serve_bundle() {  # one-shot HTTP server on the hotspot so the Mac can curl the installer
  local port="${1:-8765}" f="$BAG_HOME/bundle/blacklake-airlock-installer.sh"
  [ -f "$f" ] || fail E_USAGE "run bag.sh bundle first"
  local tok; tok="$(LC_ALL=C tr -dc 'a-z0-9' </dev/urandom | head -c 12)"
  info "On the Mac (same hotspot), run ONE of:"
  local ip
  for ip in $(local_ipv4s); do
    info "  curl -fsSLo blacklake-airlock-installer.sh http://$ip:$port/$tok && sudo bash blacklake-airlock-installer.sh"
  done
  info "Serving once (Ctrl+C to stop). Windows may ask to allow network access: allow on Private networks."
  if have powershell.exe; then
    local winf; winf="$(cygpath -w "$f" 2>/dev/null || echo "$f")"
    powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$(cygpath -w "$SKILL_DIR/scripts/serve_once.ps1" 2>/dev/null || echo "$SKILL_DIR/scripts/serve_once.ps1")" \
      -Path "$winf" -Port "$port" -Token "$tok" || fail E_SERVE "PowerShell server failed; transfer the file another way"
  elif have python3; then
    python3 - "$f" "$port" "$tok" <<'PY' || fail E_SERVE "python server failed"
import http.server, sys
path, port, tok = sys.argv[1], int(sys.argv[2]), sys.argv[3]
class H(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        if self.path.strip("/") != tok:
            self.send_response(404); self.end_headers(); return
        data = open(path, "rb").read()
        self.send_response(200); self.send_header("Content-Length", str(len(data))); self.end_headers()
        self.wfile.write(data); raise SystemExit
http.server.HTTPServer(("0.0.0.0", port), H).serve_forever()
PY
  else
    fail E_SERVE "no PowerShell or python3; transfer the file another way"
  fi
  ok "served"
}

cmd_pair() {  # pair "BAG-PAIR v=.. host=xx.local ip=1.2.3.4 fp=SHA256:... user=airlock"
  local line="$*" kv
  [ -n "$line" ] || fail E_USAGE 'bag.sh pair "<the BAG-PAIR line printed by the Mac installer>"'
  load_state
  for kv in $line; do
    case "$kv" in
      host=*) HOST="${kv#host=}";; ip=*) IP="${kv#ip=}";; fp=*) FP="${kv#fp=}";; user=*) AUSER="${kv#user=}";;
    esac
  done
  [ -n "$FP" ] || fail E_PAIR_PARSE "no fp= in the pair line"
  [ -f "$KEY" ] || fail E_LOCAL_NO_KEY "run bag.sh init and rebuild the bundle first"
  local target="" keyline="" cand
  for cand in "$HOST" "$IP"; do
    [ -z "$cand" ] || [ "$cand" = "unknown" ] && continue
    if keyline="$(keyscan_match "$cand")"; then target="$cand"; break
    elif [ $? -eq 2 ]; then fail E_HOSTKEY_MISMATCH "host $cand answered with a DIFFERENT ssh host key (wrong machine or MITM)"; fi
  done
  if [ -z "$target" ]; then
    target="$(discover)" || fail E_MAC_UNREACHABLE "Mac not reachable by name/ip and not found on local subnets (same hotspot? Mac awake? Remote Login on?)"
    keyline="$(keyscan_match "$target")"
  fi
  echo "$ALIAS $(echo "$keyline" | awk '{print $2, $3}')" > "$KNOWN"
  write_ssh_config "$target"
  case "$target" in *.local) ;; *) IP="$target";; esac
  # shellcheck disable=SC2034  # saved via ${!k} in save_state
  PAIRED_AT="$(date '+%Y-%m-%dT%H:%M:%S')"
  save_state
  local v
  v="$(gate version 2>&1)" || fail E_SSH_AUTH "ssh to airlock failed: $v (is this agent key authorized on the Mac? re-run installer)"
  info "paired with airlock $v at $target"
  sync_policy_from_mac
  hist pair "$target $v"
  ok "pair host=$target airlock_version=$v"
}

sync_policy_from_mac() {  # cache prefix/target from the Mac's config (source of truth)
  local kvs p t
  kvs="$(gate status --fast --kv 2>/dev/null)" || return 0
  p="$(echo "$kvs" | sed -n 's/^config\.branch_prefix=//p')"
  t="$(echo "$kvs" | sed -n 's/^config\.target_branch=//p')"
  [ -n "$p" ] && PREFIX="$p"
  [ -n "$t" ] && TARGET="$t"
  save_state
}

reach() {  # make sure ssh works, re-discovering the Mac if its address changed
  load_state
  [ -f "$SSHCFG" ] || [ -n "${BAG_SSH:-}" ] || return 3
  gate version >/dev/null 2>&1 && return 0
  [ -n "${BAG_SSH:-}" ] && return 1
  local cand
  for cand in "$HOST" "$IP"; do
    [ -z "$cand" ] || [ "$cand" = "unknown" ] && continue
    if keyscan_match "$cand" >/dev/null; then
      write_ssh_config "$cand"
      gate version >/dev/null 2>&1 && { info "airlock reachable at $cand"; return 0; }
    fi
  done
  local found
  if found="$(discover)"; then
    write_ssh_config "$found"; IP="$found"; save_state
    info "airlock moved: now at $found (host key verified)"
    hist rediscover "$found"
    gate version >/dev/null 2>&1 && return 0
    return 2
  fi
  return 1
}

cmd_doctor() {
  local first="" n=0
  check() {  # check <name> <code> <fix> <command...>
    local name="$1" code="$2" fix="$3"; shift 3
    if "$@" >/dev/null 2>&1; then printf 'CHECK %-22s OK\n' "$name"
    else printf 'CHECK %-22s FAIL code=%s fix=%s\n' "$name" "$code" "$fix"; [ -z "$first" ] && first="$code"; n=$((n+1)); fi
  }
  load_state
  check local.git E_LOCAL_NO_GIT "install Git for Windows" have git
  check local.ssh E_LOCAL_NO_SSH "use Git Bash (Git for Windows ships ssh)" have ssh
  check local.key E_LOCAL_NO_KEY "bag.sh init" test -f "$KEY"
  check local.paired E_NOT_PAIRED "run the Mac installer, then bag.sh pair '<BAG-PAIR line>'" test -n "$FP$( [ -n "${BAG_SSH:-}" ] && echo x)"
  if [ -z "$first" ]; then
    reach; local r=$?
    case $r in
      0) printf 'CHECK %-22s OK\n' mac.ssh; sync_policy_from_mac;;
      2) printf 'CHECK %-22s FAIL code=E_SSH_AUTH fix=%s\n' mac.ssh "Mac found but key refused: Dean re-runs installer with --add-key \"$(cat "$KEY.pub" 2>/dev/null)\""; first=E_SSH_AUTH;;
      *) printf 'CHECK %-22s FAIL code=E_MAC_UNREACHABLE fix=%s\n' mac.ssh "ask Dean: Mac awake, on the same hotspot, Remote Login on"; first=E_MAC_UNREACHABLE;;
    esac
  fi
  if [ -z "$first" ]; then
    local kvs mv
    kvs="$(gate status --kv 2>/dev/null)"
    mv="$(echo "$kvs" | sed -n 's/^version=//p')"
    printf 'CHECK %-22s %s\n' versions "skill=$BAG_VERSION airlock=${mv:-?}$( [ "$mv" != "$BAG_VERSION" ] && echo ' (MISMATCH: rebuild bundle, Dean re-runs installer)')"
    local probs; probs="$(echo "$kvs" | sed -n 's/^problem=//p')"
    if [ -z "$probs" ]; then printf 'CHECK %-22s OK\n' mac.gitlab
    else
      local p; for p in $probs; do
        printf 'CHECK %-22s FAIL code=%s fix=see references/troubleshooting.md#%s\n' mac.gitlab "$p" "$p"
        case "$p" in E_*) [ -z "$first" ] && first="$p";; esac
      done
    fi
    echo "$kvs" | grep -E '^(gitlab\.(latency_ms|error)|token\.(days_left|expires_at)|last_sync\.(ok|at|error_code)|last_sync_ok_at)=' | sed 's/^/INFO /'
  fi
  if [ -z "$first" ] && [ -n "$REPO_DIR" ]; then
    check repo.exists E_REPO_MISSING "bag.sh clone" test -d "$REPO_DIR/.git"
    check repo.fetch E_REPO_FETCH "see troubleshooting E_REPO_FETCH" git -C "$REPO_DIR" fetch -q --prune origin
  fi
  hist doctor "${first:-ok}"
  [ -z "$first" ] && ok "doctor all checks passed"
  fail "$first" "doctor found problems (fix the first failing check first)"
}

ensure_reach() {
  reach; local r=$?
  case $r in 0) return 0;; 2) fail E_SSH_AUTH "airlock refused the agent key; run bag.sh doctor";;
    3) fail E_NOT_PAIRED "not paired yet; see SKILL.md first-time setup";;
    *) fail E_MAC_UNREACHABLE "airlock Mac unreachable (asleep? different network? Remote Login off?)";; esac
}

need_repo() {  # sets D to the local clone or fails
  load_state
  [ -n "$REPO_DIR" ] && [ -d "$REPO_DIR/.git" ] || fail E_REPO_MISSING "run bag.sh clone [dir] first"
  D="$REPO_DIR"
}

cmd_clone() {
  ensure_reach
  local dir="${1:-}"
  if [ -z "$dir" ]; then
    local name; name="$(gate status --fast --kv 2>/dev/null | sed -n 's/^config\.gitlab_repo_url=//p' | sed 's#.*/##; s#\.git$##')"
    dir="$HOME/blacklake/${name:-repo}"
  fi
  if [ -d "$dir/.git" ]; then info "already cloned at $dir"
  else
    mkdir -p "$(dirname "$dir")"
    git -c core.sshCommand="$(ssh_cmd)" clone "$ALIAS:repo.git" "$dir" || fail E_REPO_FETCH "clone failed"
  fi
  git -C "$dir" config core.sshCommand "$(ssh_cmd)"
  git -C "$dir" config push.default current
  git -C "$dir" config fetch.prune true
  load_state; REPO_DIR="$(cd "$dir" && pwd)"; save_state
  hist clone "$REPO_DIR"
  ok "clone dir=$REPO_DIR"
}

cmd_sync() {
  ensure_reach
  local d out; need_repo; d="$D"
  out="$(gate sync 2>&1)"
  if ! echo "$out" | grep -q '"ok": true'; then
    local code; code="$(echo "$out" | sed -n 's/.*"error_code": "\([A-Z_]*\)".*/\1/p')"
    warn "airlock could not refresh from GitLab: ${code:-unknown} (continuing with its last snapshot)"
  fi
  git -C "$d" fetch -q --prune origin || fail E_REPO_FETCH "git fetch from airlock failed"
  local br; br="$(git -C "$d" rev-parse --abbrev-ref HEAD)"
  info "current branch: $br"
  info "origin/$TARGET: $(git -C "$d" log -1 --format='%h %s (%cr)' "origin/$TARGET" 2>/dev/null)"
  if git -C "$d" rev-parse -q --verify "origin/$br" >/dev/null; then
    info "vs origin/$br: $(git -C "$d" rev-list --left-right --count "HEAD...origin/$br" | awk '{print "ahead "$1", behind "$2}')"
  fi
  info "vs origin/$TARGET: $(git -C "$d" rev-list --left-right --count "HEAD...origin/$TARGET" | awk '{print "ahead "$1", behind "$2}')"
  ok "sync${code:+ upstream_refresh_failed=$code}"
}

slug() { echo "$1" | tr '[:upper:]' '[:lower:]' | sed -E 's#[^a-z0-9._/-]+#-#g; s#-+#-#g; s#^[-/.]+##; s#[-/.]+$##' | cut -c1-60; }

cmd_start() {  # start <topic>  -> new branch <prefix><topic> from origin/<target>
  [ $# -ge 1 ] || fail E_USAGE "bag.sh start <topic>"
  load_state
  local d topic br; need_repo; d="$D"
  topic="$(slug "$*")"; [ -n "$topic" ] || fail E_USAGE "empty topic"
  br="$PREFIX$topic"
  ( cmd_sync >/dev/null ) || warn "sync failed; branching from the last fetched origin/$TARGET"
  if [ -n "$(git -C "$d" status --porcelain)" ]; then fail E_DIRTY "working tree has uncommitted changes; commit or stash first"; fi
  if git -C "$d" rev-parse -q --verify "refs/heads/$br" >/dev/null; then
    git -C "$d" switch -q "$br" || fail E_GIT "switch failed"; info "switched to existing $br"
  elif git -C "$d" rev-parse -q --verify "refs/remotes/origin/$br" >/dev/null; then
    git -C "$d" switch -q -c "$br" --track "origin/$br" || fail E_GIT "switch failed"; info "checked out existing remote $br"
  else
    git -C "$d" switch -q -c "$br" --no-track "origin/$TARGET" || fail E_GIT "could not branch from origin/$TARGET"
    info "created $br from origin/$TARGET"
  fi
  hist start "$br"
  ok "start branch=$br"
}

cmd_push() {  # push [--title T] [--desc D] [--ready]
  ensure_reach
  load_state
  local d br; need_repo; d="$D"
  local opts=()
  while [ $# -gt 0 ]; do
    case "$1" in
      --title) opts+=(-o "mr.title=$2"); shift;;
      --desc|--description) opts+=(-o "mr.description=$(echo "$2" | tr '\r\n' '  ')"); shift;;
      --ready) opts+=(-o "mr.ready");;
      *) fail E_USAGE "unknown option $1";;
    esac; shift
  done
  br="$(git -C "$d" rev-parse --abbrev-ref HEAD)"
  case "$br" in "$PREFIX"*) ;; *) fail E_POLICY_PREFIX "current branch '$br' does not start with $PREFIX; use bag.sh start <topic>";; esac
  [ -n "$(git -C "$d" status --porcelain)" ] && warn "uncommitted changes are NOT pushed"
  local out rc
  out="$(git -C "$d" push "${opts[@]}" -u origin "HEAD:refs/heads/$br" 2>&1)"; rc=$?
  out="$(echo "$out" | sed -E 's/^remote: //; s/[[:space:]]+$//; s/\x1b\[[0-9;]*[A-Za-z]//g')"
  echo "$out" | grep -E '^AIRLOCK ' || true
  if [ $rc -eq 0 ]; then
    local mr; mr="$(echo "$out" | sed -n 's/^AIRLOCK OK .* mr=//p' | tail -1)"
    if [ -z "$mr" ] && echo "$out" | grep -q 'Everything up-to-date'; then mr="$(gate mr "$br" 2>/dev/null | sed -n 's/.*"web_url": "\(.*\)".*/\1/p' | head -1)"; info "nothing new to push"; fi
    hist push "$br ${mr:-}"
    ok "push branch=$br mr=${mr:-unknown}"
  fi
  local code; code="$(echo "$out" | sed -n 's/^AIRLOCK REJECT code=//p' | head -1)"
  if [ -z "$code" ]; then
    echo "$out" | tail -5
    code="$(echo "$out" | grep -qiE 'connection|timed out|could not read from remote' && echo E_MAC_UNREACHABLE || echo E_PUSH_UNKNOWN)"
  fi
  fail "$code" "push of $br rejected"
}

cmd_mr() {
  ensure_reach; load_state
  local br="${1:-}"; [ -n "$br" ] || { need_repo; br="$(git -C "$D" rev-parse --abbrev-ref HEAD)"; }
  gate mr "$br" || fail E_GITLAB_API "could not query MR (run bag.sh doctor)"
  ok "mr branch=$br"
}

cmd_notes() {
  ensure_reach; load_state
  local br="${1:-}"; [ -n "$br" ] || { need_repo; br="$(git -C "$D" rev-parse --abbrev-ref HEAD)"; }
  gate notes "$br" || fail E_GITLAB_API "could not read MR notes (run bag.sh doctor)"
  ok "notes branch=$br"
}

cmd_status() {
  load_state
  info "skill $BAG_VERSION  home=$BAG_HOME"
  info "airlock host=${HOST:-?} ip=${IP:-?} prefix=$PREFIX target=$TARGET repo=${REPO_DIR:-<not cloned>}"
  ensure_reach
  gate status
  ok "status"
}

cmd_log() { ensure_reach; gate log "${1:-20}"; ok "log"; }

cmd_learn() {  # learn "<what happened> -> <what fixed it>"
  [ $# -ge 1 ] || fail E_USAGE 'bag.sh learn "<symptom> -> <cause> -> <fix>"'
  printf -- '- %s  %s\n' "$(date '+%Y-%m-%d %H:%M')" "$*" >> "$BAG_HOME/learnings.md"
  ok "learned (saved to $BAG_HOME/learnings.md)"
}

cmd_version() {
  echo "skill=$BAG_VERSION"
  load_state
  if [ -f "$SSHCFG" ] || [ -n "${BAG_SSH:-}" ]; then echo "airlock=$(gate version 2>/dev/null || echo unreachable)"; fi
  ok "version"
}

usage() {
  cat <<EOF
blacklake-auto-git $BAG_VERSION — Agent side of the intranet Git airlock

First-time setup
  init                                 create the agent ssh key
  bundle --gitlab-url URL [--prefix P] [--target T]
                                       build the self-contained Mac installer
  serve-bundle [port]                  serve it once over the hotspot (Mac curls it)
  pair "<BAG-PAIR line>"               pin the Mac's host key and connect
  clone [dir]                          clone the repo from the airlock
Daily work
  sync                                 refresh from GitLab (via airlock) and fetch
  start <topic>                        new branch ${PREFIX:-deans-cc/}<topic> from origin/main
  push [--title T] [--desc D] [--ready]
                                       push current branch -> validated -> GitLab Draft MR
  mr [branch]  |  notes [branch]       MR state / review comments (JSON)
Health & learning
  doctor                               layered self-check with fix codes
  status | log [n] | version
  learn "<symptom> -> <cause> -> <fix>" record a new environment fact
EOF
}

main() {
  local c="${1:-help}"; shift || true
  case "$c" in
    init) cmd_init "$@";; bundle) cmd_bundle "$@";; serve-bundle) cmd_serve_bundle "$@";;
    pair) cmd_pair "$@";; clone) cmd_clone "$@";; sync) cmd_sync "$@";; start) cmd_start "$@";;
    push) cmd_push "$@";; mr) cmd_mr "$@";; notes) cmd_notes "$@";; doctor) cmd_doctor "$@";;
    status) cmd_status "$@";; log) cmd_log "$@";; learn) cmd_learn "$@";; version) cmd_version "$@";;
    help|-h|--help) load_state; usage;;
    *) usage; fail E_USAGE "unknown command $c";;
  esac
}
main "$@"
