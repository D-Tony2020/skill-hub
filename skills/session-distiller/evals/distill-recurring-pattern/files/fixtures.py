class Session:
    def __init__(self, sid, cwd, branch="main", start="2026-11-01T09:00:00Z"):
        self.sid, self.cwd, self.branch = sid, cwd, branch
        self.recs, self.parent = [], None
        self.t = 0
        self.day = start[:10]

    def _ts(self):
        self.t += 1
        return f"{self.day}T09:{self.t // 60:02d}:{self.t % 60:02d}.000Z"

    def _base(self, typ, **kw):
        u = str(uuid.uuid4())
        r = {"type": typ, "uuid": u, "parentUuid": self.parent, "sessionId": self.sid, "cwd": self.cwd,
             "gitBranch": self.branch, "version": "2.1.300", "isSidechain": False, "userType": "external",
             "timestamp": self._ts()}
        r.update(kw)
        self.parent = u
        self.recs.append(r)
        return r

    def user(self, text, **kw):
        return self._base("user", message={"role": "user", "content": text}, **kw)

    def assistant_text(self, text, **kw):
        return self._base("assistant", message={"id": "msg_" + uuid.uuid4().hex[:8], "role": "assistant",
                                                "model": "claude-opus-5-5", "content": [{"type": "text", "text": text}]}, **kw)

    def tool(self, name, inp, result="ok", error=False, **kw):
        tid = "toolu_" + uuid.uuid4().hex[:10]
        self._base("assistant", message={"id": "msg_" + uuid.uuid4().hex[:8], "role": "assistant", "model": "claude-opus-5-5",
                                         "content": [{"type": "tool_use", "id": tid, "name": name, "input": inp}]}, **kw)
        self._base("user", message={"role": "user", "content": [
            {"type": "tool_result", "tool_use_id": tid, "content": result, "is_error": error}]}, **kw)

    def write(self, root: Path):
        d = root / self.cwd.replace("/", "-").replace(":", "-").replace("\\", "-")
        d.mkdir(parents=True, exist_ok=True)
        p = d / f"{self.sid}.jsonl"
        with open(p, "w", encoding="utf-8") as f:
            for r in self.recs:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        return p


